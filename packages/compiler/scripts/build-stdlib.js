// Generates `stdlib.js` and `stdlib.d.ts` from `packages/stdlib/zena/**/*.zena`.

import {readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join, relative, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(__dirname, '..');
const stdlibDir = resolve(pkgRoot, '../stdlib/zena');

function collectStdlibFiles(dir, base, out) {
  const entries = readdirSync(dir, {withFileTypes: true}).sort((a, b) =>
    a.name.localeCompare(b.name),
  );
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      collectStdlibFiles(full, base, out);
    } else if (entry.name.endsWith('.zena')) {
      const rel = relative(base, full).replaceAll('\\', '/');
      out[`/stdlib/${rel}`] = readFileSync(full, 'utf8');
    }
  }
}

const files = {};
collectStdlibFiles(stdlibDir, stdlibDir, files);

const jsOut = join(pkgRoot, 'stdlib.js');
const dtsOut = join(pkgRoot, 'stdlib.d.ts');

const jsContent =
  '// Generated by scripts/build-stdlib.js — do not edit.\n' +
  `export const stdlibFiles = ${JSON.stringify(files)};\n` +
  'export default stdlibFiles;\n';

const dtsContent =
  '// Generated by scripts/build-stdlib.js — do not edit.\n' +
  'export declare const stdlibFiles: Record<string, string>;\n' +
  'export default stdlibFiles;\n';

const writeIfChanged = (outPath, content) => {
  try {
    if (readFileSync(outPath, 'utf8') === content) return;
  } catch {}
  writeFileSync(outPath, content, 'utf8');
};

writeIfChanged(jsOut, jsContent);
writeIfChanged(dtsOut, dtsContent);
